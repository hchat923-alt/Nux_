export const DEFAULT_MODEL_ID = 'claude-sonnet-5';

export function getModelById(id: string, dynamicModels: AIModel[] = []): AIModel {
  if (!id) return AVAILABLE_MODELS[0];

  // Check in dynamic / discovered models first
  const dynamicMatch = dynamicModels.find((m) => m.id === id || m.name === id);
  if (dynamicMatch) return dynamicMatch;

  // Try direct match in standard list
  const direct = AVAILABLE_MODELS.find((m) => m.id === id);
  if (direct) return direct;

  // If it's an ollama custom model ID (ollama:model_name)
  if (id.startsWith('ollama:')) {
    const rawName = id.replace(/^ollama:/, '');
    return {
      id,
      name: rawName,
      provider: 'Ollama',
      description: `نموذج محلي مثبت عبر Ollama (${rawName}).`,
      descriptionEn: `Local model installed via Ollama (${rawName}).`,
      badge: 'محلي',
      badgeEn: 'Local',
      contextWindow: 'Local',
      iconType: 'ollama',
      isLocal: true,
    };
  }

  // If it's an OpenRouter custom model ID (openrouter:provider/model)
  if (id.startsWith('openrouter:')) {
    const rawName = id.replace(/^openrouter:/, '');
    return {
      id,
      name: rawName,
      provider: 'OpenRouter',
      description: `نموذج سحابي متاح عبر منصة OpenRouter (${rawName}).`,
      descriptionEn: `Cloud model accessible via OpenRouter platform (${rawName}).`,
      badge: 'OpenRouter',
      badgeEn: 'OpenRouter',
      contextWindow: 'OpenRouter',
      iconType: 'openrouter',
    };
  }

  // If it's a Groq custom model ID (groq:model_id)
  if (id.startsWith('groq:')) {
    const rawName = id.replace(/^groq:/, '');
    const isArabic = rawName.includes('arabic') || rawName.includes('orpheus') || rawName.includes('saudi');
    const isReasoning = rawName.includes('r1') || rawName.includes('deepseek') || rawName.includes('distill');
    return {
      id,
      name: `${rawName} (Groq)`,
      provider: 'Groq',
      description: isArabic
        ? `نموذج متخصص في اللغة العربية مسرّع عبر معالجات Groq LPU (${rawName}).`
        : `نموذج فائق السرعة عبر معالجات Groq LPU (${rawName}).`,
      descriptionEn: `Ultra-fast model powered by Groq LPU architecture (${rawName}).`,
      badge: isArabic ? 'عربي متخصص' : isReasoning ? 'استدلال Groq' : 'Groq LPU',
      badgeEn: isArabic ? 'Arabic AI' : isReasoning ? 'Groq Reasoning' : 'Groq LPU',
      contextWindow: '131K',
      iconType: 'groq',
    };
  }

  // If it's a SambaNova model ID (sambanova:model_id)
  if (id.startsWith('sambanova:')) {
    const rawName = id.replace(/^sambanova:/, '');
    const isDeepSeek = rawName.toLowerCase().includes('deepseek');
    return {
      id,
      name: `${rawName} (SambaNova)`,
      provider: 'SambaNova',
      description: isDeepSeek
        ? `نموذج استدلال وتحليل منطقي فائق السرعة مسرّع عبر شرائح SambaNova SN40L (${rawName}).`
        : `نموذج ذكاء اصطناعي فائق السرعة مسرّع عبر معالجات SambaNova (${rawName}).`,
      descriptionEn: `High-throughput AI inference via SambaNova SN40L chips (${rawName}).`,
      badge: isDeepSeek ? 'DeepSeek SN' : 'SambaNova',
      badgeEn: isDeepSeek ? 'DeepSeek SN' : 'SambaNova',
      contextWindow: '128K',
      iconType: 'sambanova',
    };
  }

  // If it's a Pollinations model ID
  if (id.startsWith('pollinations:')) {
    const rawName = id.replace(/^pollinations:/, '');
    const officialMatch = AVAILABLE_MODELS.find(
      (m) => m.provider === 'Pollinations' && (m.id === id || m.id === `pollinations:${rawName}`)
    );
    if (officialMatch) return officialMatch;
    return {
      id,
      name: `${rawName} (Pollinations)`,
      provider: 'Pollinations',
      description: `نموذج نصي متاح عبر شبكة Pollinations AI (${rawName}).`,
      descriptionEn: `Text model running on Pollinations AI (${rawName}).`,
      badge: 'مجاني',
      badgeEn: 'Free',
      contextWindow: '128K',
      iconType: 'pollinations',
    };
  }

  // If it's a Gratisfy model ID
  if (id.startsWith('gratisfy:')) {
    const rawName = id.replace(/^gratisfy:/, '');
    const officialMatch = AVAILABLE_MODELS.find(
      (m) => m.provider === 'Gratisfy' && (m.id === id || m.id === `gratisfy:${rawName}`)
    );
    if (officialMatch) return officialMatch;
    return {
      id,
      name: `${rawName} (Gratisfy)`,
      provider: 'Gratisfy',
      description: `نموذج متاح عبر وسيط Gratisfy (${rawName}).`,
      descriptionEn: `Model running via Gratisfy AI router (${rawName}).`,
      badge: 'مجاني',
      badgeEn: 'Free',
      contextWindow: '128K',
      iconType: 'gratisfy',
    };
  }

  // Normalized matching for previous IDs
  const normalized = id.toLowerCase().replace(/[^a-z0-9]/g, '');
  const match = AVAILABLE_MODELS.find((m) => {
    const mNorm = m.id.toLowerCase().replace(/[^a-z0-9]/g, '');
    return mNorm === normalized || mNorm.includes(normalized) || normalized.includes(mNorm);
  });

  return match || AVAILABLE_MODELS.find((m) => m.id === DEFAULT_MODEL_ID) || AVAILABLE_MODELS[0];
}
